-- Where a ListenBrainz import stopped, so the next import for the same account carries on.
--
-- An import fetches at most 100 pages of 100 listens. Before this column, a history longer
-- than that was cut off at 10.000 listens and the run still reported `completed`; nothing
-- recorded how far it had got, so the next run started at the newest listen again and was
-- cut off at the same place. The router now stores the Unix timestamp of the oldest listen
-- reached after every page, ends a capped run as `truncated`, and starts the next import for
-- that account below it. Mirrored in scrobbler.init_db for a database that predates this file.
--
-- Re-runnable: scripts/deploy.sh applies it on every deploy.
ALTER TABLE scrobble_imports ADD COLUMN IF NOT EXISTS oldest_listened_ts BIGINT NULL;
