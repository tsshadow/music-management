#!/usr/bin/env python3
"""Emit every derived MuMa icon file from one description of the mark.

The mark is five bars whose top edge traces an M: the outer bars are tallest and the
middle bar is shortest. Inverting that reads as a V, which is how an earlier attempt
failed, so the geometry lives here once and every delivered file is generated from it.

Two coordinate systems are in play. The branding SVGs draw the mark full-bleed in a 512
viewport. The Android adaptive-icon foreground draws the same mark scaled by SAFE_ZONE
about the centre, because only the middle 72 of 108dp is guaranteed visible under the
launcher's mask.

The green SVGs in docs/branding are the hand-authored design source and are deliberately
not written here; the constants below mirror them, and the test asserts they still agree.

Run from anywhere:

    python3 tools/render_branding_icons.py

It rewrites its outputs in place; the results are committed. Pass --check to fail instead
of writing, which is what the test uses.
"""

from __future__ import annotations

import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parents[1]
RES = REPO / "services/muma-mobile/app/src/main/res"
# The debug build type overlays main: a same-named drawable here replaces the release one,
# so the aliases in the manifest need no build-type awareness at all.
RES_DEBUG = REPO / "services/muma-mobile/app/src/debug/res"
BRANDING = REPO / "docs/branding"

# The mark, full-bleed in a 512 viewport: (centre x, top y). All bars end at BOTTOM.
BARS = [(132.0, 177.0), (194.0, 227.0), (256.0, 275.0), (318.0, 227.0), (380.0, 177.0)]
BOTTOM = 335.0
STROKE = 36.0
DISC_RADIUS = 212.0
CENTRE = 256.0

# An adaptive icon only guarantees the middle 72 of its 108dp, so the Android foreground
# draws the same mark shrunk about the centre. 0.83 is what the committed icon uses.
SAFE_ZONE = 0.83

GREEN = "#1DB954"
INDIGO = "#3F51B5"
BACKDROP = "#121212"

# The debug build keeps the bars but drains the colour: a debug install next to the release
# one on a phone or Android Auto used to be told apart only by the label, which the car does
# not show. The two greys keep the icon-colour setting testable in debug. The badge is a D
# drawn as strokes in the bars' style, on a dark disc ringed in the disc colour so it reads
# as a badge rather than as the bars bleeding into it.
DEBUG_GREY = "#9E9E9E"
DEBUG_BLUE_GREY = "#78909C"
BADGE_CENTRE = 344.0
BADGE_RING_RADIUS = 80.0
BADGE_RADIUS = 68.0
BADGE_STROKE = 16.0
BADGE_GLYPH_HALF_HEIGHT = 36.0
BADGE_GLYPH_STEM = -16.0  # stem x, relative to the badge centre

# The missing-artwork placeholder sits in a cover slot, so it is deliberately dull: the
# panel greys from app.css, not a brand colour. It used to be the Spotify wordmark.
PLACEHOLDER_DISC = "#282828"
PLACEHOLDER_BARS = "#181818"

GENERATED = "Generated by tools/render_branding_icons.py; do not hand-edit."


def _scaled(value: float) -> float:
    """Moves a coordinate into the adaptive icon's safe zone."""
    return CENTRE + (value - CENTRE) * SAFE_ZONE


def _circle_path(fill_hex: str, cx: float, cy: float, radius: float) -> str:
    return f"""    <path
        android:fillColor="{fill_hex}"
        android:pathData="M{cx:.1f},{cy - radius:.1f} \
A{radius:.1f},{radius:.1f} 0 1,1 {cx - 0.1:.1f},{cy - radius:.1f} Z"/>"""


def _debug_badge(disc_hex: str) -> str:
    """A D in the lower right of the disc, inside the safe zone so no mask crops it.

    The glyph is a filled even-odd outline rather than a stroked stem-plus-arc: a stroke
    path that arcs back onto its own start renders as a filled bowl on Android.
    """
    centre = _scaled(BADGE_CENTRE)
    stem = centre + BADGE_GLYPH_STEM * SAFE_ZONE
    half = BADGE_GLYPH_HALF_HEIGHT * SAFE_ZONE
    width = BADGE_STROKE * SAFE_ZONE / 2

    def d_outline(inset: float) -> str:
        radius = half - inset
        return (
            f"M{stem - inset:.1f},{centre - radius:.1f} H{stem:.1f} "
            f"A{radius:.1f},{radius:.1f} 0 0,1 {stem:.1f},{centre + radius:.1f} "
            f"H{stem - inset:.1f} Z"
        )

    return "\n".join(
        [
            _circle_path(disc_hex, centre, centre, BADGE_RING_RADIUS * SAFE_ZONE),
            _circle_path(BACKDROP, centre, centre, BADGE_RADIUS * SAFE_ZONE),
            f"""    <path
        android:fillColor="{disc_hex}"
        android:fillType="evenOdd"
        android:pathData="{d_outline(-width)} {d_outline(width)}"/>""",
        ]
    )


def render_launcher_foreground(disc_hex: str, debug: bool = False) -> str:
    """The adaptive-icon foreground: a coloured disc with the bars drawn over it."""
    radius = DISC_RADIUS * SAFE_ZONE
    bars = "\n".join(
        f"""    <path
        android:strokeColor="{BACKDROP}"
        android:strokeWidth="{STROKE * SAFE_ZONE:.1f}"
        android:strokeLineCap="round"
        android:pathData="M{_scaled(x):.1f} {_scaled(top):.1f} V{_scaled(BOTTOM):.1f}"/>"""
        for x, top in BARS
    )
    if debug:
        bars += "\n" + _debug_badge(disc_hex)
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- {GENERATED} -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="512"
    android:viewportHeight="512">
    <path
        android:fillColor="{disc_hex}"
        android:pathData="M{CENTRE:.1f},{CENTRE - radius:.1f} \
A{radius:.1f},{radius:.1f} 0 1,1 {CENTRE - 0.1:.1f},{CENTRE - radius:.1f} Z"/>
{bars}
</vector>
"""


def render_notification_glyph() -> str:
    """The status bar glyph: bars only, white, fitted to a 24dp box with 1dp padding."""
    left = BARS[0][0] - STROKE / 2
    right = BARS[-1][0] + STROKE / 2
    top = min(bar_top for _, bar_top in BARS) - STROKE / 2
    scale = (24.0 - 2.0) / (right - left)
    height = (BOTTOM + STROKE / 2 - top) * scale
    x_offset = 1.0
    y_offset = (24.0 - height) / 2

    def place_x(x: float) -> float:
        return (x - left) * scale + x_offset

    def place_y(y: float) -> float:
        return (y - top) * scale + y_offset

    paths = "\n".join(
        f"""    <path
        android:strokeColor="#FFFFFFFF"
        android:strokeWidth="{STROKE * scale:.2f}"
        android:strokeLineCap="round"
        android:pathData="M{place_x(x):.2f},{place_y(bar_top):.2f} V{place_y(BOTTOM):.2f}"/>"""
        for x, bar_top in BARS
    )
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- {GENERATED} -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="24"
    android:viewportHeight="24">
{paths}
</vector>
"""


def _svg_bars(stroke_hex: str) -> str:
    return "\n".join(
        f'  <path d="M{x:.1f} {top:.1f} V{BOTTOM:.1f}" fill="none" stroke="{stroke_hex}" '
        f'stroke-width="{STROKE:.1f}" stroke-linecap="round"/>'
        for x, top in BARS
    )


def render_disc_svg(disc_hex: str) -> str:
    """The square mark: a disc on the app backdrop, with the bars masked out of it."""
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" \
width="512" height="512">
  <title>MuMa</title>
  <defs>
    <mask id="bars">
      <rect width="512" height="512" fill="#000"/>
      <circle cx="{CENTRE:.0f}" cy="{CENTRE:.0f}" r="{DISC_RADIUS:.0f}" fill="#fff"/>
{_svg_bars("#000")}
    </mask>
  </defs>
  <rect width="512" height="512" fill="{BACKDROP}"/>
  <circle cx="{CENTRE:.0f}" cy="{CENTRE:.0f}" r="{DISC_RADIUS:.0f}" fill="{disc_hex}" \
mask="url(#bars)"/>
</svg>
"""


def render_round_svg(disc_hex: str) -> str:
    """The round mark: the disc fills the frame and the bars are painted on top."""
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" \
width="512" height="512">
  <title>MuMa</title>
  <circle cx="{CENTRE:.0f}" cy="{CENTRE:.0f}" r="{CENTRE:.0f}" fill="{disc_hex}"/>
{_svg_bars(BACKDROP)}
</svg>
"""


def render_placeholder_svg() -> str:
    """The missing-artwork placeholder: the round mark in panel greys, in a 24 viewport."""
    scale = 24.0 / (CENTRE * 2)
    bars = "\n".join(
        f'  <path d="M{x * scale:.3f} {top * scale:.3f} V{BOTTOM * scale:.3f}" fill="none" '
        f'stroke="{PLACEHOLDER_BARS}" stroke-width="{STROKE * scale:.3f}" '
        f'stroke-linecap="round"/>'
        for x, top in BARS
    )
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" \
width="24" height="24">
  <title>MuMa</title>
  <circle cx="12" cy="12" r="12" fill="{PLACEHOLDER_DISC}"/>
{bars}
</svg>
"""


# Every copy of the placeholder that something actually reads. The web UI asks for
# /images/... at the server root, so the LMS docroot copy is the one a browser gets; the
# frontend's own public/ copy ships in dist/ and approot/ is what the artwork service
# falls back to (see lms/main.cpp).
PLACEHOLDER_COPIES = [
    REPO / "services/frontend/public/images/spotify-fallback.svg",
    REPO / "services/frontend/public/images/unknown-cover.svg",
    REPO / "services/music-management-server/docroot/images/spotify-fallback.svg",
    REPO / "services/music-management-server/docroot/images/unknown-cover.svg",
    REPO / "services/music-management-server/approot/images/spotify-fallback.svg",
    REPO / "services/music-management-server/approot/images/unknown-cover.svg",
]

OUTPUTS = {
    RES / "drawable/ic_launcher_foreground.xml": lambda: render_launcher_foreground(GREEN),
    RES / "drawable/ic_launcher_foreground_blue.xml": lambda: render_launcher_foreground(INDIGO),
    RES_DEBUG / "drawable/ic_launcher_foreground.xml": lambda: render_launcher_foreground(DEBUG_GREY, debug=True),
    RES_DEBUG / "drawable/ic_launcher_foreground_blue.xml": lambda: render_launcher_foreground(
        DEBUG_BLUE_GREY, debug=True
    ),
    RES / "drawable/ic_stat_ultrasonic.xml": render_notification_glyph,
    RES / "drawable/media3_notification_small_icon.xml": render_notification_glyph,
    BRANDING / "muma-icon-blue.svg": lambda: render_disc_svg(INDIGO),
    BRANDING / "muma-icon-round-blue.svg": lambda: render_round_svg(INDIGO),
    **dict.fromkeys(PLACEHOLDER_COPIES, render_placeholder_svg),
}


def main(argv: list[str]) -> int:
    check = "--check" in argv
    stale = []
    for path, render in OUTPUTS.items():
        wanted = render()
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != wanted:
                stale.append(path)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(wanted, encoding="utf-8")
    for path in stale:
        print(f"stale: {path.relative_to(REPO)}")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
